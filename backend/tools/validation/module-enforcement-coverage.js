#!/usr/bin/env node
/**
 * Company Plans / Packages — module enforcement coverage (Phase B).
 *
 * Package enforcement (`RequireModuleGuard` + the per-Company resolver) only
 * works on a route where `CompanyContextGuard` has already validated the
 * Membership and set `request.companyContext`. A controller that carries
 * `@RequireModule` but NOT `CompanyContextGuard` still enforces only the
 * INSTALLATION licence — a Company's package is not applied there. Hiding a
 * menu entry or returning 404 is not protection by itself: this tool lists, from
 * the source, exactly which domain controllers are protected per Company and
 * which are not, so the gap is a documented, countable blocker rather than an
 * assumption.
 *
 * Usage:  node tools/validation/module-enforcement-coverage.js [--write <file.md>]
 * Exit 1 if a company-scoped domain controller is missing `@RequireModule`
 * (a Company-scoped route that could skip entitlement entirely).
 * Also exported (`scan`, `render`) for the regression spec.
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'src');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.controller\.ts$/.test(e.name)) out.push(p);
  }
  return out;
}

/** One row per domain controller file. */
function scan() {
  const rows = [];
  for (const file of walk(path.join(SRC, 'domains'))) {
    const s = fs.readFileSync(file, 'utf8');
    const rel = path.relative(SRC, file).split(path.sep).join('/');
    const prefixes = [...s.matchAll(/@Controller\(\s*(?:'([^']*)'|"([^"]*)")?\s*\)/g)].map((m) => m[1] ?? m[2] ?? '');
    const modules = [...new Set([...s.matchAll(/@RequireModule\('([a-z]+)'\)/g)].map((m) => m[1]))].sort();
    const guards = [...s.matchAll(/@UseGuards\(([^)]*)\)/g)].map((m) => m[1]).join(',');
    rows.push({
      file: rel,
      domain: rel.split('/')[1],
      routes: prefixes.filter((p) => p !== '').join(', ') || '(root)',
      modules,
      companyScoped: /CompanyContextGuard/.test(guards),
    });
  }
  return rows.sort((a, b) => a.file.localeCompare(b.file));
}

function violations(rows) {
  return rows.filter((r) => r.companyScoped && r.modules.length === 0);
}

function render(rows) {
  const scoped = rows.filter((r) => r.companyScoped);
  const platform = rows.filter((r) => !r.companyScoped);
  const byModule = new Map();
  for (const r of rows) {
    for (const m of r.modules.length ? r.modules : ['(no @RequireModule)']) {
      if (!byModule.has(m)) byModule.set(m, { scoped: 0, platform: 0 });
      byModule.get(m)[r.companyScoped ? 'scoped' : 'platform']++;
    }
  }
  let md = '# Module enforcement coverage (generated)\n\n';
  md += 'Generated by `backend/tools/validation/module-enforcement-coverage.js` from the controller sources — do not edit by hand.\n\n';
  md += `Domain controllers: **${rows.length}** — company-scoped (package enforced per Company): **${scoped.length}** · platform-scoped (only the installation licence is enforced; Area 21 dependency): **${platform.length}**.\n\n`;
  md += '## Per module\n\n| Module | Company-scoped controllers | Platform-scoped controllers | Package enforced for the module? |\n|---|---|---|---|\n';
  for (const [m, c] of [...byModule.entries()].sort()) {
    const state = c.platform === 0 ? 'Yes — all controllers' : c.scoped === 0 ? '**No — none**' : '**Partial**';
    md += `| ${m} | ${c.scoped} | ${c.platform} | ${state} |\n`;
  }
  md += '\n## Platform-scoped controllers (blockers before commercial activation of per-Company packages)\n\n| Controller | Routes | Module guard |\n|---|---|---|\n';
  for (const r of platform) md += `| \`${r.file.replace('domains/', '')}\` | ${r.routes} | ${r.modules.join(', ') || '—'} |\n`;
  md += '\n## Company-scoped controllers (package enforced)\n\n| Controller | Routes | Module guard |\n|---|---|---|\n';
  for (const r of scoped) md += `| \`${r.file.replace('domains/', '')}\` | ${r.routes} | ${r.modules.join(', ') || '**MISSING**'} |\n`;
  return md;
}

module.exports = { scan, violations, render };

if (require.main === module) {
  const rows = scan();
  const bad = violations(rows);
  const i = process.argv.indexOf('--write');
  if (i !== -1) {
    fs.writeFileSync(process.argv[i + 1], render(rows));
    console.log(`wrote ${process.argv[i + 1]}`);
  }
  console.log(`domain controllers: ${rows.length} | company-scoped: ${rows.filter((r) => r.companyScoped).length} | platform-scoped: ${rows.filter((r) => !r.companyScoped).length}`);
  if (bad.length) {
    console.error('VIOLATION — company-scoped controller without @RequireModule:\n' + bad.map((r) => '  ' + r.file).join('\n'));
    process.exit(1);
  }
}
